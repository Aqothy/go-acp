package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"maps"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

type schema map[string]any

type rootSchema struct {
	Defs map[string]schema `json:"$defs"`
}

type metaFile struct {
	Version         int               `json:"version"`
	AgentMethods    map[string]string `json:"agentMethods"`
	ClientMethods   map[string]string `json:"clientMethods"`
	ProtocolMethods map[string]string `json:"protocolMethods"`
}

type kind int

const (
	kindAny kind = iota
	kindScalar
	kindStruct
	kindSlice
	kindMap
)

type typeInfo struct {
	Type     string
	Kind     kind
	Nullable bool
}

type propInfo struct {
	JSONName         string
	Schemas          []schema
	RequiredRoot     bool
	VariantTotal     int
	PresentVariants  int
	RequiredVariants int
}

type generator struct {
	defs      map[string]schema
	meta      metaFile
	kindCache map[string]kind
}

func main() {
	schemaPath := flag.String("schema", "schema/schema.json", "path to ACP JSON schema")
	metaPath := flag.String("meta", "schema/meta.json", "path to ACP metadata JSON")
	outPath := flag.String("out", "schema/generated.go", "output Go file")
	flag.Parse()

	var root rootSchema
	mustReadJSON(*schemaPath, &root)
	var meta metaFile
	mustReadJSON(*metaPath, &meta)

	g := &generator{defs: root.Defs, meta: meta, kindCache: map[string]kind{}}
	src, err := g.generate()
	if err != nil {
		fatal(err)
	}
	formatted, err := format.Source(src)
	if err != nil {
		_, _ = os.Stderr.Write(src)
		fatal(fmt.Errorf("format generated source: %w", err))
	}
	if err := os.WriteFile(*outPath, formatted, 0o644); err != nil {
		fatal(err)
	}
}

func mustReadJSON(path string, v any) {
	data, err := os.ReadFile(path)
	if err != nil {
		fatal(err)
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.UseNumber()
	if err := dec.Decode(v); err != nil {
		fatal(fmt.Errorf("decode %s: %w", path, err))
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}

func (g *generator) generate() ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by acp-schema-gen; DO NOT EDIT.\n")
	b.WriteString("// Source: schema.json and meta.json from the Agent Client Protocol schema release.\n\n")
	b.WriteString("package schema\n\n")
	b.WriteString("import \"encoding/json\"\n\n")
	b.WriteString("// RawMessage contains an arbitrary JSON value whose concrete ACP shape is schema-dependent.\n")
	b.WriteString("type RawMessage = json.RawMessage\n\n")
	b.WriteString("// Method is an ACP JSON-RPC method name.\n")
	b.WriteString("type Method string\n\n")
	g.writeMethodConstants(&b)

	names := make([]string, 0, len(g.defs))
	for name := range g.defs {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		if err := g.writeDef(&b, name, g.defs[name]); err != nil {
			return nil, fmt.Errorf("generate %s: %w", name, err)
		}
	}
	return []byte(b.String()), nil
}

func (g *generator) writeMethodConstants(b *strings.Builder) {
	fmt.Fprintf(b, "// ProtocolVersionCurrent is the ACP protocol version described by meta.json.\nconst ProtocolVersionCurrent = %d\n\n", g.meta.Version)
	writeGroup := func(prefix string, methods map[string]string) {
		keys := make([]string, 0, len(methods))
		for k := range methods {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		fmt.Fprintf(b, "const (\n")
		for _, key := range keys {
			fmt.Fprintf(b, "\t%sMethod%s Method = %q\n", prefix, goName(key), methods[key])
		}
		fmt.Fprintf(b, ")\n\n")
		fmt.Fprintf(b, "var %sMethods = map[string]Method{\n", prefix)
		for _, key := range keys {
			fmt.Fprintf(b, "\t%q: %sMethod%s,\n", key, prefix, goName(key))
		}
		fmt.Fprintf(b, "}\n\n")
	}
	writeGroup("Agent", g.meta.AgentMethods)
	writeGroup("Client", g.meta.ClientMethods)
	writeGroup("Protocol", g.meta.ProtocolMethods)
}

func (g *generator) writeDef(b *strings.Builder, name string, s schema) error {
	doc(b, name, stringValue(s["description"]))
	if scalar, ok := g.scalarUnion(s); ok {
		fmt.Fprintf(b, "type %s %s\n\n", name, scalar.base)
		g.writeScalarConstants(b, name, scalar)
		return nil
	}

	if isObjectSchema(s) || g.isObjectUnion(s) {
		props := g.collectProperties(s)
		if len(props) == 0 && hasAdditionalProperties(s) {
			fmt.Fprintf(b, "type %s map[string]any\n\n", name)
			return nil
		}
		fmt.Fprintf(b, "type %s struct {\n", name)
		propNames := make([]string, 0, len(props))
		for p := range props {
			propNames = append(propNames, p)
		}
		sort.Strings(propNames)
		usedFields := map[string]int{}
		for _, jsonName := range propNames {
			p := props[jsonName]
			required := p.RequiredRoot
			if p.VariantTotal > 0 && p.PresentVariants == p.VariantTotal && p.RequiredVariants == p.VariantTotal {
				required = true
			}
			typ := g.mergedPropertyType(p.Schemas, required)
			field := goName(jsonName)
			if n := usedFields[field]; n > 0 {
				field = fmt.Sprintf("%s%d", field, n+1)
			}
			usedFields[goName(jsonName)]++
			tag := jsonName
			if !required {
				tag += ",omitempty"
			}
			fmt.Fprintf(b, "\t%s %s `json:%q`\n", field, typ, tag)
		}
		fmt.Fprintf(b, "}\n\n")
		g.writeObjectUnionConstants(b, name, s)
		return nil
	}

	info := g.typeInfoForSchema(s)
	if info.Type == "any" {
		fmt.Fprintf(b, "type %s any\n\n", name)
		return nil
	}
	fmt.Fprintf(b, "type %s %s\n\n", name, info.Type)
	return nil
}

type scalarUnionInfo struct {
	base      string
	constants []scalarConst
}

type scalarConst struct {
	Name  string
	Value any
	Title string
}

func (g *generator) scalarUnion(s schema) (scalarUnionInfo, bool) {
	if ref, ok := s["$ref"].(string); ok {
		return g.scalarUnion(g.defs[refName(ref)])
	}
	if t, ok := s["type"].(string); ok {
		switch t {
		case "string":
			return scalarUnionInfo{base: "string", constants: enumConstants(s)}, true
		case "integer":
			return scalarUnionInfo{base: integerType(s), constants: enumConstants(s)}, true
		case "number":
			return scalarUnionInfo{base: "float64", constants: enumConstants(s)}, true
		case "boolean":
			return scalarUnionInfo{base: "bool", constants: enumConstants(s)}, true
		}
	}
	variants, ok := unionVariants(s)
	if !ok || len(variants) == 0 {
		return scalarUnionInfo{}, false
	}
	base := ""
	var constants []scalarConst
	for _, v := range variants {
		if stringValue(v["type"]) == "null" {
			return scalarUnionInfo{}, false
		}
		vt := stringValue(v["type"])
		if vt == "" && len(v) == 1 && v["title"] != nil {
			return scalarUnionInfo{}, false
		}
		var vb string
		switch vt {
		case "string":
			vb = "string"
		case "integer":
			vb = integerType(v)
		case "number":
			vb = "float64"
		case "boolean":
			vb = "bool"
		default:
			return scalarUnionInfo{}, false
		}
		if base == "" {
			base = vb
		} else if base != vb {
			return scalarUnionInfo{}, false
		}
		if c, ok := v["const"]; ok {
			constants = append(constants, scalarConst{Value: normalizeNumber(c), Title: stringValue(v["title"])})
		}
	}
	return scalarUnionInfo{base: base, constants: constants}, true
}

func enumConstants(s schema) []scalarConst {
	var out []scalarConst
	if values, ok := s["enum"].([]any); ok {
		for _, v := range values {
			out = append(out, scalarConst{Value: normalizeNumber(v)})
		}
	}
	if c, ok := s["const"]; ok {
		out = append(out, scalarConst{Value: normalizeNumber(c), Title: stringValue(s["title"])})
	}
	return out
}

func normalizeNumber(v any) any {
	if n, ok := v.(json.Number); ok {
		if i, err := n.Int64(); err == nil {
			return i
		}
		if f, err := strconv.ParseFloat(n.String(), 64); err == nil {
			return f
		}
	}
	return v
}

func (g *generator) writeScalarConstants(b *strings.Builder, typeName string, info scalarUnionInfo) {
	if len(info.constants) == 0 {
		return
	}
	seen := map[string]bool{}
	b.WriteString("const (\n")
	for _, c := range info.constants {
		namePart := c.Title
		if namePart == "" {
			namePart = fmt.Sprint(c.Value)
		}
		constName := typeName + goName(namePart)
		if seen[constName] {
			continue
		}
		seen[constName] = true
		switch v := c.Value.(type) {
		case string:
			fmt.Fprintf(b, "\t%s %s = %q\n", constName, typeName, v)
		case int64:
			fmt.Fprintf(b, "\t%s %s = %d\n", constName, typeName, v)
		case float64:
			fmt.Fprintf(b, "\t%s %s = %g\n", constName, typeName, v)
		case bool:
			fmt.Fprintf(b, "\t%s %s = %t\n", constName, typeName, v)
		}
	}
	b.WriteString(")\n\n")
}

func (g *generator) writeObjectUnionConstants(b *strings.Builder, typeName string, s schema) {
	variants, ok := unionVariants(s)
	if !ok {
		return
	}
	seen := map[string]bool{}
	var lines []string
	for _, v := range variants {
		props := asSchemaMap(v["properties"])
		for jsonName, ps := range props {
			c, ok := ps["const"]
			if !ok {
				continue
			}
			propName := goName(jsonName)
			name := typeName
			if propName != typeName {
				name += propName
			}
			name += goName(fmt.Sprint(c))
			if seen[name] {
				continue
			}
			seen[name] = true
			switch v := normalizeNumber(c).(type) {
			case string:
				lines = append(lines, fmt.Sprintf("\t%s = %q\n", name, v))
			case int64:
				lines = append(lines, fmt.Sprintf("\t%s = %d\n", name, v))
			}
		}
	}
	if len(lines) == 0 {
		return
	}
	sort.Strings(lines)
	b.WriteString("const (\n")
	for _, line := range lines {
		b.WriteString(line)
	}
	b.WriteString(")\n\n")
}

func (g *generator) collectProperties(s schema) map[string]*propInfo {
	props := map[string]*propInfo{}
	add := func(jsonName string, ps schema, required bool) {
		p := props[jsonName]
		if p == nil {
			p = &propInfo{JSONName: jsonName}
			props[jsonName] = p
		}
		p.Schemas = append(p.Schemas, ps)
		if required {
			p.RequiredRoot = true
		}
	}
	rootReq := requiredSet(s)
	for jsonName, ps := range asSchemaMap(s["properties"]) {
		add(jsonName, ps, rootReq[jsonName])
	}
	for _, ref := range allOfRefs(s) {
		for jsonName, rp := range g.collectProperties(g.defs[ref]) {
			add(jsonName, mergedSchema(rp.Schemas), rp.RequiredRoot)
		}
	}
	variants, hasVariants := unionVariants(s)
	if hasVariants {
		variantTotal := len(variants)
		for _, v := range variants {
			vp := g.collectVariantProperties(v)
			for jsonName, p := range vp {
				dst := props[jsonName]
				if dst == nil {
					dst = &propInfo{JSONName: jsonName}
					props[jsonName] = dst
				}
				dst.VariantTotal = variantTotal
				dst.Schemas = append(dst.Schemas, p.Schemas...)
				dst.PresentVariants++
				if p.RequiredRoot {
					dst.RequiredVariants++
				}
			}
		}
	}
	return props
}

func (g *generator) collectVariantProperties(s schema) map[string]*propInfo {
	props := map[string]*propInfo{}
	add := func(jsonName string, ps schema, required bool) {
		p := props[jsonName]
		if p == nil {
			p = &propInfo{JSONName: jsonName}
			props[jsonName] = p
		}
		p.Schemas = append(p.Schemas, ps)
		if required {
			p.RequiredRoot = true
		}
	}
	req := requiredSet(s)
	for jsonName, ps := range asSchemaMap(s["properties"]) {
		add(jsonName, ps, req[jsonName])
	}
	for _, ref := range allOfRefs(s) {
		for jsonName, rp := range g.collectProperties(g.defs[ref]) {
			add(jsonName, mergedSchema(rp.Schemas), rp.RequiredRoot)
		}
	}
	return props
}

func mergedSchema(schemas []schema) schema {
	if len(schemas) == 1 {
		return schemas[0]
	}
	return schema{"anyOf": schemaSliceToAny(schemas)}
}

func schemaSliceToAny(schemas []schema) []any {
	out := make([]any, len(schemas))
	for i, s := range schemas {
		out[i] = s
	}
	return out
}

func (g *generator) mergedPropertyType(schemas []schema, required bool) string {
	if len(schemas) == 0 {
		return "any"
	}
	var chosen typeInfo
	for i, s := range schemas {
		info := g.typeInfoForSchema(s)
		if info.Nullable {
			required = false
		}
		if i == 0 {
			chosen = info
			continue
		}
		if chosen.Type != info.Type {
			if scalarCompatible(chosen.Type, info.Type) {
				chosen.Type = scalarCommon(chosen.Type, info.Type)
				chosen.Kind = kindScalar
			} else {
				chosen = typeInfo{Type: "any", Kind: kindAny}
			}
		}
	}
	return applyOptional(chosen, required)
}

func scalarCompatible(a, b string) bool {
	return scalarCommon(a, b) != ""
}

func scalarCommon(a, b string) string {
	if a == b {
		return a
	}
	stringsSet := map[string]bool{"string": true}
	intsSet := map[string]bool{"int64": true, "int": true, "uint64": true, "uint32": true, "uint16": true}
	floatsSet := map[string]bool{"float64": true}
	if stringsSet[a] && stringsSet[b] {
		return "string"
	}
	if intsSet[a] && intsSet[b] {
		return "int64"
	}
	if (intsSet[a] || floatsSet[a]) && (intsSet[b] || floatsSet[b]) {
		return "float64"
	}
	return ""
}

func (g *generator) typeInfoForSchema(s schema) typeInfo {
	if s == nil {
		return typeInfo{Type: "any", Kind: kindAny}
	}
	if ref, ok := s["$ref"].(string); ok {
		name := refName(ref)
		return typeInfo{Type: name, Kind: g.kindOfDef(name)}
	}
	if refs := allOfRefs(s); len(refs) == 1 && s["type"] == nil && s["properties"] == nil && s["oneOf"] == nil && s["anyOf"] == nil {
		name := refs[0]
		return typeInfo{Type: name, Kind: g.kindOfDef(name)}
	}
	if variants, ok := unionVariants(s); ok {
		nonNull := make([]schema, 0, len(variants))
		nullable := false
		for _, v := range variants {
			if stringValue(v["type"]) == "null" {
				nullable = true
			} else {
				nonNull = append(nonNull, v)
			}
		}
		if len(nonNull) == 1 {
			info := g.typeInfoForSchema(nonNull[0])
			info.Nullable = info.Nullable || nullable
			return info
		}
		if scalar, ok := g.scalarUnion(s); ok {
			return typeInfo{Type: scalar.base, Kind: kindScalar, Nullable: nullable}
		}
		if g.isObjectUnion(s) {
			return typeInfo{Type: "RawMessage", Kind: kindAny, Nullable: nullable}
		}
		return typeInfo{Type: "any", Kind: kindAny, Nullable: nullable}
	}
	if types, ok := stringList(s["type"]); ok {
		nullable := false
		var nonNull []string
		for _, t := range types {
			if t == "null" {
				nullable = true
			} else {
				nonNull = append(nonNull, t)
			}
		}
		if len(nonNull) == 1 {
			info := g.typeInfoForSchema(schemaWithType(s, nonNull[0]))
			info.Nullable = info.Nullable || nullable
			return info
		}
		return typeInfo{Type: "any", Kind: kindAny, Nullable: nullable}
	}
	switch stringValue(s["type"]) {
	case "string":
		return typeInfo{Type: "string", Kind: kindScalar}
	case "integer":
		return typeInfo{Type: integerType(s), Kind: kindScalar}
	case "number":
		return typeInfo{Type: "float64", Kind: kindScalar}
	case "boolean":
		return typeInfo{Type: "bool", Kind: kindScalar}
	case "array":
		item := g.typeInfoForSchema(toSchema(s["items"]))
		return typeInfo{Type: "[]" + item.Type, Kind: kindSlice}
	case "object":
		if hasAdditionalProperties(s) && len(asSchemaMap(s["properties"])) == 0 {
			return typeInfo{Type: "map[string]any", Kind: kindMap}
		}
		return typeInfo{Type: "RawMessage", Kind: kindAny}
	case "null":
		return typeInfo{Type: "any", Kind: kindAny, Nullable: true}
	}
	return typeInfo{Type: "any", Kind: kindAny}
}

func schemaWithType(s schema, typ string) schema {
	out := schema{}
	maps.Copy(out, s)
	out["type"] = typ
	return out
}

func applyOptional(info typeInfo, required bool) string {
	typ := info.Type
	if typ == "" {
		typ = "any"
	}
	if !required || info.Nullable {
		switch info.Kind {
		case kindScalar, kindStruct:
			if !strings.HasPrefix(typ, "*") {
				typ = "*" + typ
			}
		}
	}
	return typ
}

func (g *generator) kindOfDef(name string) kind {
	if k, ok := g.kindCache[name]; ok {
		return k
	}
	g.kindCache[name] = kindAny // cycle guard
	s := g.defs[name]
	if _, ok := g.scalarUnion(s); ok {
		g.kindCache[name] = kindScalar
		return kindScalar
	}
	if isObjectSchema(s) || g.isObjectUnion(s) {
		g.kindCache[name] = kindStruct
		return kindStruct
	}
	info := g.typeInfoForSchema(s)
	g.kindCache[name] = info.Kind
	return info.Kind
}

func (g *generator) isObjectUnion(s schema) bool {
	variants, ok := unionVariants(s)
	if !ok {
		return false
	}
	objectSeen := false
	for _, v := range variants {
		if stringValue(v["type"]) == "null" {
			continue
		}
		if stringValue(v["type"]) == "object" || len(asSchemaMap(v["properties"])) > 0 || len(allOfRefs(v)) > 0 {
			objectSeen = true
			continue
		}
		return false
	}
	return objectSeen
}

func isObjectSchema(s schema) bool {
	return stringValue(s["type"]) == "object" || (len(asSchemaMap(s["properties"])) > 0 && !hasOnlyUnion(s))
}

func hasOnlyUnion(s schema) bool {
	_, one := s["oneOf"]
	_, any := s["anyOf"]
	return (one || any) && s["type"] == nil && s["properties"] == nil
}

func hasAdditionalProperties(s schema) bool {
	v, ok := s["additionalProperties"].(bool)
	return ok && v
}

func allOfRefs(s schema) []string {
	arr, ok := s["allOf"].([]any)
	if !ok {
		return nil
	}
	var refs []string
	for _, item := range arr {
		if ref, ok := toSchema(item)["$ref"].(string); ok {
			refs = append(refs, refName(ref))
		}
	}
	return refs
}

func unionVariants(s schema) ([]schema, bool) {
	if arr, ok := s["oneOf"].([]any); ok {
		return anySliceToSchemas(arr), true
	}
	if arr, ok := s["anyOf"].([]any); ok {
		return anySliceToSchemas(arr), true
	}
	return nil, false
}

func anySliceToSchemas(arr []any) []schema {
	out := make([]schema, 0, len(arr))
	for _, item := range arr {
		out = append(out, toSchema(item))
	}
	return out
}

func asSchemaMap(v any) map[string]schema {
	raw, ok := v.(map[string]any)
	if !ok {
		return nil
	}
	out := map[string]schema{}
	for k, val := range raw {
		if m, ok := val.(map[string]any); ok {
			out[k] = schema(m)
		}
	}
	return out
}

func toSchema(v any) schema {
	if s, ok := v.(schema); ok {
		return s
	}
	if m, ok := v.(map[string]any); ok {
		return schema(m)
	}
	return nil
}

func requiredSet(s schema) map[string]bool {
	out := map[string]bool{}
	arr, ok := s["required"].([]any)
	if !ok {
		return out
	}
	for _, v := range arr {
		if str, ok := v.(string); ok {
			out[str] = true
		}
	}
	return out
}

func stringValue(v any) string {
	if s, ok := v.(string); ok {
		return s
	}
	return ""
}

func stringList(v any) ([]string, bool) {
	arr, ok := v.([]any)
	if !ok {
		return nil, false
	}
	out := make([]string, 0, len(arr))
	for _, item := range arr {
		str, ok := item.(string)
		if !ok {
			return nil, false
		}
		out = append(out, str)
	}
	return out, true
}

func refName(ref string) string {
	idx := strings.LastIndex(ref, "/")
	if idx == -1 {
		return ref
	}
	return ref[idx+1:]
}

func integerType(s schema) string {
	if f := stringValue(s["format"]); strings.HasPrefix(f, "uint") {
		switch f {
		case "uint16":
			return "uint16"
		case "uint32":
			return "uint32"
		case "uint64":
			return "uint64"
		}
	}
	min, hasMin := numberAsFloat(s["minimum"])
	max, hasMax := numberAsFloat(s["maximum"])
	if hasMin && min >= 0 && hasMax {
		if max <= 65535 {
			return "uint16"
		}
		if max <= 4294967295 {
			return "uint32"
		}
		return "uint64"
	}
	return "int64"
}

func numberAsFloat(v any) (float64, bool) {
	switch n := v.(type) {
	case json.Number:
		f, err := strconv.ParseFloat(n.String(), 64)
		return f, err == nil
	case float64:
		return n, true
	case int:
		return float64(n), true
	case int64:
		return float64(n), true
	}
	return 0, false
}

func doc(b *strings.Builder, name, description string) {
	if description == "" {
		fmt.Fprintf(b, "// %s is generated from the ACP JSON schema.\n", name)
		return
	}
	lines := strings.Split(strings.TrimSpace(description), "\n")
	for i, line := range lines {
		line = strings.TrimRight(line, " ")
		if i == 0 && !strings.HasPrefix(line, name) {
			line = name + " " + lowerFirst(line)
		}
		if line == "" {
			fmt.Fprintln(b, "//")
		} else {
			fmt.Fprintf(b, "// %s\n", line)
		}
	}
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}

var splitRe = regexp.MustCompile(`[A-Za-z0-9]+`)

var initialisms = map[string]string{
	"acp": "ACP", "api": "API", "auth": "Auth", "cwd": "CWD", "fs": "FS", "http": "HTTP", "https": "HTTPS", "id": "ID", "json": "JSON", "llm": "LLM", "mcp": "MCP", "nes": "NES", "rpc": "RPC", "sse": "SSE", "tui": "TUI", "uri": "URI", "url": "URL", "utf": "UTF", "ws": "WS",
}

func goName(s string) string {
	if s == "_meta" {
		return "Meta"
	}
	parts := splitIdentifier(s)
	if len(parts) == 0 {
		return "Value"
	}
	var out strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		lp := strings.ToLower(p)
		if repl, ok := initialisms[lp]; ok {
			out.WriteString(repl)
			continue
		}
		if isAllDigits(p) {
			out.WriteString(p)
			continue
		}
		out.WriteString(strings.ToUpper(p[:1]))
		if len(p) > 1 {
			out.WriteString(p[1:])
		}
	}
	name := out.String()
	if name == "" {
		name = "Value"
	}
	if r := rune(name[0]); r >= '0' && r <= '9' {
		name = "Value" + name
	}
	return name
}

func splitIdentifier(s string) []string {
	raw := splitRe.FindAllString(s, -1)
	var out []string
	for _, token := range raw {
		out = append(out, splitCamel(token)...)
	}
	return out
}

func splitCamel(s string) []string {
	if s == "" {
		return nil
	}
	var parts []string
	start := 0
	runes := []rune(s)
	for i := 1; i < len(runes); i++ {
		prev, cur := runes[i-1], runes[i]
		nextLower := i+1 < len(runes) && unicode.IsLower(runes[i+1])
		if (unicode.IsLower(prev) && unicode.IsUpper(cur)) || (unicode.IsUpper(prev) && unicode.IsUpper(cur) && nextLower) || (unicode.IsLetter(prev) && unicode.IsDigit(cur)) || (unicode.IsDigit(prev) && unicode.IsLetter(cur)) {
			parts = append(parts, string(runes[start:i]))
			start = i
		}
	}
	parts = append(parts, string(runes[start:]))
	return parts
}

func isAllDigits(s string) bool {
	for _, r := range s {
		if r < '0' || r > '9' {
			return false
		}
	}
	return s != ""
}
